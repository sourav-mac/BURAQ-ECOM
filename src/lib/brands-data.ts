/**
 * Filter helper to get verified brands for active display
 */
export function getVerifiedBrands(category?: BrandCategory | "all"): BrandItem[] {
  const verified = BRANDS_CATALOGUE.filter((b) => b.status === "verified");
  if (!category || category === "all") return verified;
  return verified.filter((b) => b.category === category);
}

/**
 * Helper to get unconfirmed/draft candidate brands for admin/reporting
 */
export function getUnconfirmedBrands(): BrandItem[] {
  return BRANDS_CATALOGUE.filter((b) => b.status === "candidate_unconfirmed");
}
